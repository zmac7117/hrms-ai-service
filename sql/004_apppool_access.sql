-- Lets the IIS application pool read and write the database (Windows authentication).
USE master;
IF SUSER_ID('IIS APPPOOL\HRMSAI-Api') IS NULL
    CREATE LOGIN [IIS APPPOOL\HRMSAI-Api] FROM WINDOWS;
GO
USE HrmsAi;
IF DATABASE_PRINCIPAL_ID('IIS APPPOOL\HRMSAI-Api') IS NULL
    CREATE USER [IIS APPPOOL\HRMSAI-Api] FOR LOGIN [IIS APPPOOL\HRMSAI-Api];
ALTER ROLE db_datareader ADD MEMBER [IIS APPPOOL\HRMSAI-Api];
ALTER ROLE db_datawriter ADD MEMBER [IIS APPPOOL\HRMSAI-Api];
GO